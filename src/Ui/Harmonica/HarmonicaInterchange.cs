//           as-is. A grid imported from .gam is an arbitrary scatter, which is what ContourGrid was
//           built for (§6.4).
//  R-h7-13  Export testbench must produce a RUNNABLE .cnl that reproduces the current harmonicaRF
//           state through the ordinary HB path. HarmonicaContext.NetlistText is the OPEN-port form;
