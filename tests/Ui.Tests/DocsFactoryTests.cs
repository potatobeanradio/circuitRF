    /// body). The decks are the one part of this pipeline that is NOT regenerated by the routine
    /// <c>--out docs/user</c> command and whose output is git-ignored, so nothing else in the repo
    /// would notice a deck that has stopped building.
    /// </summary>
    private static IEnumerable<(string Path, string Head, string Body)> DeckSources()
    {
        string dir = Path.Combine(DocsRoot(), "src", "slides");
        if (!Directory.Exists(dir)) yield break;

        foreach (var path in Directory.EnumerateFiles(dir, "*.md", SearchOption.AllDirectories)
                                      .OrderBy(p => p, StringComparer.Ordinal))
        {
            var text = File.ReadAllText(path).Replace("\r\n", "\n");
            int end = text.IndexOf("\n---", 4, StringComparison.Ordinal);
            if (!text.StartsWith("---\n", StringComparison.Ordinal) || end < 0) continue;
            yield return (path, text[4..end], text[(end + 4)..]);
        }
    }

    private static string FrontMatter(string head, string key)
    {
        foreach (var raw in head.Split('\n'))
        {
            var line = raw.Trim();
            int colon = line.IndexOf(':');
            if (colon > 0 && line[..colon].Trim() == key) return line[(colon + 1)..].Trim();
        }
        return "";
    }

    /// <summary>
    /// <b>Every deck the command line documents still exists.</b>
    ///
    /// <para><c>--deck overview</c> and its three siblings are advertised in the tool's own usage
    /// text and in the design note. A renamed or deleted source would make one of them an error the
    /// day somebody typed it, and nothing else here would fail: decks are built on demand and their
    /// PDFs are git-ignored, so the routine gate never touches them.</para>
    /// </summary>
    [Theory]
    [InlineData("overview")]
    [InlineData("new-user")]
    [InlineData("quick-start")]
    [InlineData("reference")]
    public void EveryDocumentedDeckIdHasASource(string deck)
    {
        var decks = DeckSources()
                   .Where(d => FrontMatter(d.Head, "kind") == "slides")
                   .Select(d => FrontMatter(d.Head, "deck"))
                   .ToList();

        Assert.True(decks.Contains(deck),
            $"No slide source declares 'deck: {deck}', so "
          + $"`dotnet run --project tools/DocGen -- --slides docs/slides --deck {deck}` now fails. "
          + $"Sources found: {(decks.Count == 0 ? "(none)" : string.Join(", ", decks))}.");
    }

    /// <summary>
    /// <b>Every deck declares a deck id, and no two decks share one.</b> A slides page without one
    /// can only ever be built as part of "all" — which is the state <c>--deck</c> exists to fix —
    /// and two pages sharing an id would build one and silently skip the other.
    /// </summary>
    [Fact]
    public void DeckIdsAreDeclaredAndUnique()
    {
        var ids = new List<string>();
        foreach (var (path, head, _) in DeckSources())
        {
            if (FrontMatter(head, "kind") != "slides") continue;
            var id = FrontMatter(head, "deck");
            Assert.True(id.Length > 0,
                $"{Path.GetFileName(path)} is a 'kind: slides' page with no 'deck:' id in its front-matter.");
            ids.Add(id);
        }

        var dupes = ids.GroupBy(i => i).Where(g => g.Count() > 1).Select(g => g.Key).ToList();
        Assert.True(dupes.Count == 0,
            "Two slide sources declare the same deck id, so --deck would build one of them and "
          + "silently skip the other: " + string.Join(", ", dupes));
    }

    /// <summary>
    /// <b>Every figure a deck cites is in the catalog, and every deck placeholder is one the deck
    /// backend knows.</b>
    ///
    /// <para>The generator raises both of these, but only when a deck is actually built — and a deck
    /// is built on demand. This is the gate that fails in the routine suite the moment a
    /// <c>FigureCatalog</c> row is renamed out from under a slide.</para>
    /// </summary>
    [Fact]
    public void EveryDeckPlaceholderResolves()
    {
        var known    = FigureCatalog.Catalog.Select(r => r.Id).ToHashSet(StringComparer.Ordinal);
        var problems = new List<string>();

        foreach (var (path, _, body) in DeckSources())
        {
            string name = Path.GetFileName(path);
            foreach (System.Text.RegularExpressions.Match m in Regex.Matches(body, @"\{\{\s*(?<kind>[a-z]+)\s*:\s*(?<arg>[^}]*)\}\}"))
            {
                var kind = m.Groups["kind"].Value;
                if (kind is not ("ui" or "caption" or "stats"))
                {
                    problems.Add($"{name}: placeholder '{kind}' is not one a deck understands "
                               + "(ui, caption, stats).");
                    continue;
                }
                if (kind != "ui") continue;

                var id = m.Groups["arg"].Value.Split('|')[0].Trim();
                if (!known.Contains(id))
                    problems.Add($"{name}: figure '{id}' is not in FigureCatalog.");
            }
        }

        Assert.True(problems.Count == 0, string.Join("\n", problems));
    }

    /// <summary>
    /// <b>A slide's caption belongs to a figure on the same slide.</b> A caption with no figure is
    /// not an error the backend can raise — it simply never draws — so the sentence disappears and
    /// the deck still generates cleanly.
    /// </summary>
    [Fact]
    public void EveryDeckCaptionSitsOnASlideThatHasAFigure()
    {
        var orphans = new List<string>();

        foreach (var (path, _, body) in DeckSources())
        {
            bool figureOnThisSlide = false;
            foreach (var raw in body.Split('\n'))
            {
                var line = raw.Trim();
                if (line.StartsWith("#", StringComparison.Ordinal)) { figureOnThisSlide = false; continue; }
                if (Regex.IsMatch(line, @"^\{\{\s*ui\s*:")) { figureOnThisSlide = true; continue; }
                if (Regex.IsMatch(line, @"^\{\{\s*caption\s*:") && !figureOnThisSlide)
                    orphans.Add($"{Path.GetFileName(path)}: {line}");
            }
        }

        Assert.True(orphans.Count == 0,
            "These captions are on a slide with no figure, so they are silently dropped:\n  "
          + string.Join("\n  ", orphans));
    }

    /// <summary>
    /// <b>A documentation schematic is not a template.</b>
    ///
    /// <para><c>src/Ui/resources/doc-schematics/*.csch</c> exist so a user-doc figure can photograph a
    /// two-component circuit a reader is about to build. They are embedded exactly like the shipped
    /// templates and <c>ShippedSchematicTemplates.Discover</c> scans every embedded <c>.csch</c>, so
    /// the ONLY thing keeping them out of the template picker is the logical-name filter. Dropping
    /// that filter would add teaching examples to the product's template list silently — a product
    /// change made by accident, which is precisely the class of thing a gate is for.</para>
    /// </summary>
    [Fact]
    public void DocumentationSchematicsAreNotOfferedAsTemplates()
    {
        var offered = ShippedSchematicTemplates.All.Select(t => t.Id).ToList();

        string dir = Path.Combine(RepoRoot(), "src", "Ui", "resources", "doc-schematics");
        Assert.True(Directory.Exists(dir),
            $"{dir} is missing, so every figure built on a documentation schematic has no source.");

        var docStems = Directory.EnumerateFiles(dir, "*.csch")
                                .Select(Path.GetFileNameWithoutExtension)
                                .ToList();
        Assert.NotEmpty(docStems);

        var leaked = docStems.Where(stem => offered.Contains(stem!)).ToList();
        Assert.True(leaked.Count == 0,
            "These documentation-only schematics are being offered in the template picker: "
          + string.Join(", ", leaked) + ". They are embedded with a distinct LogicalName so "
          + "ShippedSchematicTemplates.Discover can skip them; that filter has been lost.");

        // …and each one still loads through the real reader, which is the whole reason they are
        // files rather than hand-built view-models.
        foreach (var stem in docStems)
        {
            var model = ShippedSchematicTemplates.LoadDocSchematic(stem!);
            Assert.True(model.Components.Count > 0,
                $"Documentation schematic '{stem}' parsed to an empty circuit.");
        }
    }

    // ── Documentation search ─────────────────────────────────────────────────
    //
    // The search is two halves that have to agree: a GENERATED index
    // (assets/js/search-index.js, rebuilt by tools/DocGen) and a HAND-WRITTEN reader
    // (assets/js/docs-search.js). Neither announces its own failure — a stale index
    // sends readers to anchors that no longer exist, a missing script leaves a search
    // box that silently does nothing, and both look completely normal in a browser
    // until you type. These gates are what notice.

    private static string SearchIndexPath() => Path.Combine(DocsRoot(), "assets", "js", "search-index.js");
    private static string SearchScriptPath() => Path.Combine(DocsRoot(), "assets", "js", "docs-search.js");

    /// <summary>The index's payload, parsed out of the one assignment the generated file contains.</summary>
    private static JsonElement SearchIndexJson()
    {
        string js = File.ReadAllText(SearchIndexPath());
        int eq = js.IndexOf("window.CRF_DOCS_SEARCH = ", StringComparison.Ordinal);
        Assert.True(eq >= 0,
            "search-index.js does not assign window.CRF_DOCS_SEARCH. docs-search.js reads exactly that "
          + "global and gives up silently when it is absent, so the search boxes would never appear.");

        string json = js[(eq + "window.CRF_DOCS_SEARCH = ".Length)..].TrimEnd().TrimEnd(';');
        return JsonDocument.Parse(json).RootElement.Clone();
    }

    /// <summary>
    /// <b>Every search result must land on an anchor that exists.</b>
    ///
    /// <para>This is the same failure the Help-button gate above catches, arriving by a different
    /// road: a section is renamed or an explicit <c>{#id}</c> changes, the index still carries the
    /// old anchor, and every result for that section opens the page scrolled to the top with no
    /// error anywhere. Regenerating fixes it — which is exactly why the check has to be automatic,
    /// because nobody re-reads 450 search results by hand.</para>
    /// </summary>
    [Fact]
    public void EverySearchResultResolvesToAnAnchorInTheShippedPages()
    {
        var offered = new HashSet<string>(StringComparer.Ordinal);
        foreach (var page in AllPages())
        {
            string rel = Path.GetRelativePath(DocsRoot(), page).Replace(Path.DirectorySeparatorChar, '/');
            offered.Add(rel);
            foreach (System.Text.RegularExpressions.Match m in Regex.Matches(File.ReadAllText(page), @"id=""(?<id>[^""]+)"""))
                offered.Add(rel + "#" + m.Groups["id"].Value);
        }

        var root = SearchIndexJson();
        var pages = root.GetProperty("p").EnumerateArray().Select(p => p[0].GetString()!).ToList();

        var broken = new List<string>();
        foreach (var s in root.GetProperty("s").EnumerateArray())
        {
            string slug = pages[s[0].GetInt32()];
            string anchor = s[1].GetString()!;
            string link = anchor.Length == 0 ? slug : slug + "#" + anchor;
            if (!offered.Contains(link)) broken.Add($"{link}  (\"{s[2].GetString()}\")");
        }

        Assert.True(broken.Count == 0,
            "These search results point at anchors that are not in the shipped HTML, so choosing one "
          + "opens the page at the top and says nothing. Re-run tools/DocGen:\n  "
          + string.Join("\n  ", broken));
    }

    /// <summary>
    /// <b>The index must cover the whole reading order.</b>
    ///
    /// <para>A page missing from it is unfindable while looking completely normal to a reader who
    /// arrives by a link — the exact invisibility the reading-order orphan check exists to prevent
    /// on the navigation side.</para>
    /// </summary>
    [Fact]
    public void TheSearchIndexCoversEveryPageInTheReadingOrder()
    {
        var indexed = SearchIndexJson().GetProperty("p").EnumerateArray()
                                       .Select(p => p[0].GetString()!)
                                       .ToHashSet(StringComparer.Ordinal);

        var expected = AllPages()
            .Select(p => Path.GetRelativePath(DocsRoot(), p).Replace(Path.DirectorySeparatorChar, '/'))
            .ToList();

        var missing = expected.Where(p => !indexed.Contains(p)).ToList();
        Assert.True(missing.Count == 0,
            "These pages ship but are not in the search index, so nothing a reader types can find "
          + "them:\n  " + string.Join("\n  ", missing));
    }

    /// <summary>
    /// <b>No figure geometry may reach the index.</b>
    ///
    /// <para>Pages are ~1 MB each because their figures are inlined as <c>&lt;svg&gt;</c>. The
    /// extraction removes those by counting tag depth, and if that ever stops working the index does
    /// not break — it silently grows by two orders of magnitude, ships to every reader, and matches
    /// queries against path coordinates. A size ceiling plus a look for path data catches both
    /// halves of that.</para>
    /// </summary>
    [Fact]
    public void TheSearchIndexCarriesProseAndNotFigureGeometry()
    {
        long bytes = new FileInfo(SearchIndexPath()).Length;
        Assert.True(bytes < 1_500_000,
            $"search-index.js is {bytes:N0} bytes. It holds the prose of ~33 pages and should be well "
          + "under a megabyte; this size means figure geometry is being indexed as text.");

        var offenders = new List<string>();
        var root = SearchIndexJson();
        var pages = root.GetProperty("p").EnumerateArray().Select(p => p[0].GetString()!).ToList();

        foreach (var s in root.GetProperty("s").EnumerateArray())
        {
            string text = s[3].GetString()!;
            // Three consecutive SVG coordinate pairs: prose does not contain this and path data is
            // nothing but this.
            if (Regex.IsMatch(text, @"(-?\d+\.\d+[ ,]+){6}"))
                offenders.Add($"{pages[s[0].GetInt32()]}#{s[1].GetString()}");
        }

        Assert.True(offenders.Count == 0,
            "These indexed sections contain SVG path data rather than prose:\n  "
          + string.Join("\n  ", offenders));
    }

    /// <summary>
    /// <b>Every page carries the search box and both scripts, at the right relative depth.</b>
    ///
    /// <para>The docs are opened from a web host, from the loopback server the Help menu starts, and
    /// straight off disk, so every reference between them is relative. A wrong number of
    /// <c>../</c> segments is invisible on the landing page and broken everywhere below it.</para>
    /// </summary>
    [Fact]
    public void EveryPageCarriesTheSearchBoxAndItsScripts()
    {
        var offenders = new List<string>();
        foreach (var page in AllPages())
        {
            string rel  = Path.GetRelativePath(DocsRoot(), page).Replace(Path.DirectorySeparatorChar, '/');
            string html = File.ReadAllText(page);
            string depth = string.Concat(Enumerable.Repeat("../", rel.Count(c => c == '/')));

            if (!html.Contains("class=\"doc-search\" data-crf-search", StringComparison.Ordinal))
                offenders.Add($"{rel}: no header search box");
            if (!html.Contains($"data-root=\"{depth}\"", StringComparison.Ordinal))
                offenders.Add($"{rel}: search box data-root is not \"{depth}\", so every result would "
                            + "link to the wrong place");
            foreach (var script in new[] { "search-index.js", "docs-search.js" })
                if (!html.Contains($"src=\"{depth}assets/js/{script}\"", StringComparison.Ordinal))
                    offenders.Add($"{rel}: does not load {depth}assets/js/{script}");
        }

        Assert.True(offenders.Count == 0,
            "The search is wired wrongly on these pages:\n  " + string.Join("\n  ", offenders));
    }

    /// <summary>
