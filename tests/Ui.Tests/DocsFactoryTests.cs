    /// <summary>
    /// <b>No shipped figure may carry a trailing separator on a per-glyph <c>x</c>/<c>y</c> list.</b>
    ///
    /// <para>Owner-reported, 2026-08-21: figure text "missing or else really small" in Firefox on
    /// Ubuntu, while macOS and Windows were perfect. Skia's SVG device writes
    /// <c>x="0, 8.11, ..., 87.37, "</c> — an SVG <c>list-of-coordinates</c> may not end in a
    /// separator, Gecko applies strict error handling and drops the whole attribute, and every run is
    /// then drawn at the element origin a line above its baseline, where the control's clip removes
    /// all but a sliver of each glyph. Blink and WebKit accept it, so the two platforms whose default
    /// browsers are Edge and Safari looked fine; it reproduces in Firefox on every platform.
    /// <c>SvgFontNormalizer.TrimCoordinateLists</c> is the repair.</para>
    ///
    /// <para>This gate is over the ARTEFACTS, not the normaliser (which has its own unit tests),
    /// because the failure that actually reaches a reader is a figure regenerated by an older build
    /// and committed — the unit tests cannot see that, and 170 files renders it invisible by hand.</para>
    /// </summary>
    [Fact]
    public void NoShippedFigureCarriesATrailingSeparatorInAPositionList()
    {
        var rx      = new Regex(@"\s(?:x|y)\s*=\s*""[^""]*[,\s]""");
        var offenders = new List<string>();

        foreach (var path in AllSvgs().Concat(AllPages()))
            if (rx.IsMatch(File.ReadAllText(path)))
                offenders.Add(Path.GetFileName(path));

        Assert.True(offenders.Count == 0,
            "These generated documents still carry Skia's trailing separator on a per-glyph x/y list, "
          + "so their text renders unreadably in Firefox — regenerate with "
          + "`dotnet run --project tools/DocGen -- --out docs/user`: "
          + string.Join(", ", offenders.Take(12)) + (offenders.Count > 12 ? $" (+{offenders.Count - 12} more)" : ""));
    }

